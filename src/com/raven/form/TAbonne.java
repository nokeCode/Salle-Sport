    // Méthode pour rafraîchir le tableau après une opération
    private void refreshTable() {
    List<Object[]> abonnes = Affichage.getAbonnes();
    table.setRowCount(0); // Vider le tableau
    for (Object[] abonne : abonnes) {
        table.addRow(abonne);
    }
}

