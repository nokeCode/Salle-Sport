    private void jButtonModActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonModActionPerformed
        // TODO add your handling code here:
        int selectedRow = table.getSelectedRow();
        if (selectedRow >= 0) {
            String nom = (String) table.getValueAt(selectedRow, 0);
            String prenom = (String) table.getValueAt(selectedRow, 1);
            String numeroTelephone = (String) table.getValueAt(selectedRow, 3);
            StatusType statut = (StatusType) table.getValueAt(selectedRow, 4);

            // Convertir le statut en String ("OUI" ou "NON")
            String statutString = (statut == StatusType.OUI) ? "OUI" : "NON";

            // Ouvrir le panel de modification avec les données de l'abonné sélectionné
            ModifAbonne modifAbonne = new ModifAbonne(nom, prenom, numeroTelephone, statutString);
            //System.out.println(modifAbonne);

            // Créer un JDialog pour afficher ModifAbonne
            JDialog dialog = new JDialog();
            dialog.setTitle("Modifier Abonné");
            dialog.setModal(true); // Rend la fenêtre modale
            dialog.setContentPane(modifAbonne); // Ajouter ModifAbonne au JDialog
            dialog.pack(); // Ajuster la taille du JDialog au contenu
            dialog.setLocationRelativeTo(null); // Centrer la fenêtre sur l'écran
            dialog.setVisible(true); // Afficher la fenêtre
            // Rafraîchir le tableau après la fermeture du JDialog
            refreshTable();
            dialog.dispose();
          
        }
        else {
            JOptionPane.showMessageDialog(this, "Veuillez sélectionner un abonné à modifier.", "Aucun abonné sélectionné", JOptionPane.WARNING_MESSAGE);
    }

    }//GEN-LAST:event_jButtonModActionPerformed

    private void jButtonSuppActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSuppActionPerformed
        // TODO add your handling code here:
        int selectedRow = table.getSelectedRow();
        if (selectedRow >= 0) {
            String numeroTelephone = (String) table.getValueAt(selectedRow, 3);
            boolean isDeleted = supprimerAbonne(numeroTelephone);
            if (isDeleted) {
                JOptionPane.showMessageDialog(this, "Abonné supprimé avec succès.", "Succès", JOptionPane.INFORMATION_MESSAGE);
                // Rafraîchir le tableau après la suppression
                refreshTable();
            } else {
                JOptionPane.showMessageDialog(this, "Erreur lors de la suppression de l'abonné.", "Erreur", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Veuillez sélectionner un abonné à supprimer.", "Aucun abonné sélectionné", JOptionPane.WARNING_MESSAGE);
        }


    }//GEN-LAST:event_jButtonSuppActionPerformed

    private void jButtonRenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonRenActionPerformed
        // TODO add your handling code here:
        int selectedRow = table.getSelectedRow();
        if (selectedRow >= 0) {
            String numeroTelephone = (String) table.getValueAt(selectedRow, 3);
            boolean isRenewed = renouvelerAbonnement(numeroTelephone);
            if (isRenewed) {
                JOptionPane.showMessageDialog(this, "Abonnement renouvelé avec succès.", "Succès", JOptionPane.INFORMATION_MESSAGE);
                // Rafraîchir le tableau après le renouvellement
                refreshTable();
            } else {
                JOptionPane.showMessageDialog(this, "Erreur lors du renouvellement de l'abonnement.", "Erreur", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Veuillez sélectionner un abonné à renouveler.", "Aucun abonné sélectionné", JOptionPane.WARNING_MESSAGE);
        }

    }//GEN-LAST:event_jButtonRenActionPerformed

